#if UNITY_EDITOR
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace LowDefMustard.Rendering.Editor
{
    [InitializeOnLoad]
    public static class BattleEffectDispatchGenerator
    {
        // Notes:
        //  - Writes the battle effect HLSL that must mirror C#:  BattleEffectDataLayout + [BattleEffectMirroredEnum] enums as defines + the shape dispatch
        //      (shape ID -> <ClassName>Distance adapter) from the BattleEffectShape subclasses
        //  - Runs after every script reload
        //  - Only writes (+ reimports) when the output changes (generated file is stable in source control)
        //  - Internal methods/properties are for test visibility

        // Const Tunables
        internal const string outputPath = "Packages/com.lowdefmustard.rendering/Runtime/Shaders/HLSLUtilities/Generated/BattleEffectDispatch.generated.hlsl";
        private const string _shapesIncludePath = "Packages/com.lowdefmustard.rendering/Runtime/Shaders/HLSLUtilities/BattleEffectShapes.hlsl";
        private const string _adapterSuffix = "Distance";
        private const string _enumPrefix = "BattleEffect";

        static BattleEffectDispatchGenerator()
        {
            EditorApplication.delayCall += () => Generate(false);
        }

        [MenuItem("Tools/Battle Effects/Regenerate Shape Dispatch", priority = 32)]
        private static void RegenerateFromMenu() => Generate(true);

        private static void Generate(bool isVerbose)
        {
            if (!TryGetShapes(out List<(int id, Type type)> shapes)) { return; }

            string output = BuildOutput(shapes);
            if (File.Exists(outputPath) && File.ReadAllText(outputPath) == output)
            {
                if (isVerbose) { Debug.Log("Battle effect shape dispatch is up to date"); }
                return;
            }

            Directory.CreateDirectory(Path.GetDirectoryName(outputPath) ?? string.Empty);
            File.WriteAllText(outputPath, output);
            AssetDatabase.ImportAsset(outputPath);
            Debug.Log($"Regenerated battle effect shape dispatch ({shapes.Count} shapes):  {outputPath}");
        }

        internal static bool TryGetShapes(out List<(int id, Type type)> shapes)
        {
            shapes = new List<(int id, Type type)>();
            bool isValid = true;
            foreach (Type type in TypeCache.GetTypesDerivedFrom<BattleEffectShape>().Where(type => !type.IsAbstract))
            {
                var shapeIdAttribute = type.GetCustomAttribute<BattleEffectShapeIdAttribute>();
                if (shapeIdAttribute == null)
                {
                    Debug.LogError($"Battle effect shape {type.Name} has no [BattleEffectShapeId] - shape dispatch not regenerated");
                    isValid = false;
                    continue;
                }
                shapes.Add((shapeIdAttribute.id, type));
            }

            foreach (IGrouping<int, (int id, Type type)> duplicate in shapes.GroupBy(shape => shape.id).Where(group => group.Count() > 1))
            {
                Debug.LogError($"Battle effect shape ID {duplicate.Key} is used by {string.Join(", ", duplicate.Select(shape => shape.type.Name))} - shape dispatch not regenerated");
                isValid = false;
            }

            shapes.Sort((left, right) => left.id.CompareTo(right.id));
            return isValid;
        }

        internal static string BuildOutput(List<(int id, Type type)> shapes)
        {
            var output = new StringBuilder();
            output.AppendLine("// <auto-generated>");
            output.AppendLine($"//  Written by {nameof(BattleEffectDispatchGenerator)} from {nameof(BattleEffectDataLayout)}, [{nameof(BattleEffectMirroredEnumAttribute)}] enums + the {nameof(BattleEffectShape)} subclasses ~ do not edit");
            output.AppendLine("// </auto-generated>");
            output.AppendLine();
            output.AppendLine("#ifndef BATTLEEFFECTDISPATCH_GENERATED_INCLUDED");
            output.AppendLine("#define BATTLEEFFECTDISPATCH_GENERATED_INCLUDED");
            output.AppendLine();
            output.AppendLine($"#include \"{_shapesIncludePath}\"");
            output.AppendLine();

            output.AppendLine($"// {nameof(BattleEffectDataLayout)}");
            foreach (FieldInfo field in typeof(BattleEffectDataLayout).GetFields(BindingFlags.Public | BindingFlags.Static).Where(field => field.IsLiteral && field.FieldType == typeof(int)))
            {
                output.AppendLine($"#define BATTLE_EFFECT_LAYOUT_{field.Name.ToUpperInvariant()} {field.GetRawConstantValue()}");
            }
            output.AppendLine();

            foreach (Type enumType in TypeCache.GetTypesWithAttribute<BattleEffectMirroredEnumAttribute>().Where(type => type.IsEnum).OrderBy(type => type.Name))
            {
                string enumName = enumType.Name.StartsWith(_enumPrefix) ? enumType.Name.Substring(_enumPrefix.Length) : enumType.Name;
                output.AppendLine($"// {enumType.Name}");
                foreach (object value in Enum.GetValues(enumType))
                {
                    output.AppendLine($"#define BATTLE_EFFECT_{enumName.ToUpperInvariant()}_{value.ToString().ToUpperInvariant()} {Convert.ToInt32(value)}");
                }
                output.AppendLine();
            }

            output.AppendLine("float BattleEffectShapeDistance(int shapeId, BattleEffectShapeInput input)");
            output.AppendLine("{");
            foreach ((int id, Type type) in shapes)
            {
                output.AppendLine($"    if (shapeId == {id}) {{ return {type.Name}{_adapterSuffix}(input); }}");
            }
            output.AppendLine("    return 1e5;");
            output.AppendLine("}");
            output.AppendLine();
            output.AppendLine("#endif");
            return output.ToString();
        }
    }
}
#endif
